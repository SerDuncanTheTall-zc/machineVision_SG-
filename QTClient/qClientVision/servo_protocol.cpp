ServoProtocol::ServoProtocol(QObject* parent)
    : QObject(parent)
{
    m_socket = new QTcpSocket(this);
    connect(m_socket, &QTcpSocket::connected,    this, &ServoProtocol::onSocketConnected);
    connect(m_socket, &QTcpSocket::disconnected, this, &ServoProtocol::onSocketDisconnected);
    connect(m_socket, &QTcpSocket::errorOccurred,this, &ServoProtocol::onSocketError);
}

ServoProtocol::~ServoProtocol()
{
    if (m_socket->state() == QAbstractSocket::ConnectedState)
        m_socket->disconnectFromHost();
}

void ServoProtocol::connectToHost(const QString& ip, quint16 port)
{
    m_socket->connectToHost(QHostAddress(ip), port);
}

void ServoProtocol::disconnectFromHost()
{
    m_socket->disconnectFromHost();
}

bool ServoProtocol::isConnected() const
{
    return m_socket->state() == QAbstractSocket::ConnectedState;
}

// --- 业务指令 ---

void ServoProtocol::servoMove(quint8 servoId, Direction dir, quint8 speed)
{
    QByteArray payload;
    payload.append(static_cast<char>(servoId));
    payload.append(static_cast<char>(dir));
    payload.append(static_cast<char>(speed));
    sendPacket(0x01, payload);
}

void ServoProtocol::servoStop(quint8 servoId)
{
    servoMove(servoId, DIR_STOP);
}

void ServoProtocol::servoAbs(quint8 servoId, qint16 pan, qint16 tilt)
{
    QByteArray payload;
    payload.append(static_cast<char>(servoId));
    payload.append(static_cast<char>((pan >> 8) & 0xFF));
    payload.append(static_cast<char>(pan & 0xFF));
    payload.append(static_cast<char>((tilt >> 8) & 0xFF));
    payload.append(static_cast<char>(tilt & 0xFF));
    sendPacket(0x02, payload);
}

void ServoProtocol::setTracking(bool enable)
{
    QByteArray payload;
    payload.append(enable ? '\x01' : '\x00');
    sendPacket(0x03, payload);
}

void ServoProtocol::setStream(bool enable, quint16 udpDataPort, quint16 udpVideoPort)
{
    QByteArray payload;
    payload.append(enable ? '\x01' : '\x00');
    payload.append(static_cast<char>((udpDataPort >> 8) & 0xFF));
    payload.append(static_cast<char>(udpDataPort & 0xFF));
    payload.append(static_cast<char>((udpVideoPort >> 8) & 0xFF));
    payload.append(static_cast<char>(udpVideoPort & 0xFF));
    sendPacket(0x04, payload);
}

void ServoProtocol::ping()
{
    sendPacket(0x05);
}

// --- 帧封装 ---

void ServoProtocol::sendPacket(quint8 cmd, const QByteArray& payload)
{
    if (!isConnected()) {
        qWarning() << "ServoProtocol: not connected, dropping packet cmd=" << cmd;
        return;
    }

    // 载荷 = cmd + payload
    QByteArray data;
    data.append(static_cast<char>(cmd));
    data.append(payload);

    quint16 len = static_cast<quint16>(data.size());

    QByteArray frame;
    frame.reserve(5 + len);
    frame.append('\xAA');
    frame.append('\x55');
    frame.append(static_cast<char>((len >> 8) & 0xFF));
    frame.append(static_cast<char>(len & 0xFF));
    frame.append(data);
    frame.append(static_cast<char>(crc8(data)));

    m_socket->write(frame);
}

quint8 ServoProtocol::crc8(const QByteArray& data)
{
    quint8 crc = 0x00;
    for (int i = 0; i < data.size(); ++i) {
        crc = s_crc8Table[crc ^ static_cast<quint8>(data[i])];
    }
    return crc;
}

// --- 内部槽 ---

void ServoProtocol::onSocketConnected()
{
    qDebug() << "ServoProtocol: connected";
    emit connected();
}

void ServoProtocol::onSocketDisconnected()
{
    qDebug() << "ServoProtocol: disconnected";
    emit disconnected();
}

void ServoProtocol::onSocketError(QAbstractSocket::SocketError err)
{
    Q_UNUSED(err);
    QString msg = m_socket->errorString();
    qWarning() << "ServoProtocol: socket error" << msg;
    emit errorOccurred(msg);
}
